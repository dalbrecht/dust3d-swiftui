/// Valid tiny PNGs constructed for this test. Frozen pixel expectations come from
/// Qt 6.12.0 QImage.scaled(KeepAspectRatio, FastTransformation), without a GUI.
/// Explicit output sizes isolate raster sampling from the separate view-fit policy.
final class ReferenceColorQtPNGFormatTests: XCTestCase {
    private struct Fixture {
        let name: String
        let png: String
        let sha256: String
        let width: Int
        let height: Int
        let expected: [UInt8]
    }

    func testFittedSpatialSamplesMatchQt() throws {
        try assertFixtures(Self.fixtures.filter { $0.name.hasPrefix("spatial-") })
    }

    func testFittedSamplesMatchQtAcrossPNGDepthsAndFormats() throws {
        try assertFixtures(Self.fixtures.filter { !$0.name.hasPrefix("spatial-") && !$0.name.hasPrefix("rgb16-key-") })
    }

    func testRGB16TransparencyPreservesEncodedSamplesDespiteQtReaderDefect() throws {
        // Qt 6.12's RGB16+tRNS reader omits transparency expansion, then treats
        // packed RGB words as RGBA64. Keep correct channels instead (#337).
        for fixture in Self.fixtures.filter({ $0.name.hasPrefix("rgb16-key-") }) {
            let png = try XCTUnwrap(Data(base64Encoded: fixture.png))
            let document = try Dust3DDocument(data: Dust3DDocument.emptyArchive())
                .applying(.setReferenceImagePNG(png))
            let prepared = try ReferenceColorRasterCodec.prepare(
                document: document, fittedSize: ReferencePixelSize(width: fixture.width, height: fixture.height))
            let expected: [UInt8]
            if fixture.width == 2 {
                expected = [17, 83, 201, 0, 201, 83, 17, 255]
            } else {
                let row: [UInt8] = [0, 0, 0, 0, 0, 0, 0, 0, 201, 83, 17, 255, 201, 83, 17, 255]
                expected = row + row
            }
            XCTAssertNotEqual(fixture.expected, expected, "Frozen Qt reader discrepancy remains explicit")
            XCTAssertEqual(Array(prepared.raster.pixels), expected, fixture.name)
        }
    }

    private func assertFixtures(_ fixtures: [Fixture]) throws {
        for fixture in fixtures {
            let png = try XCTUnwrap(Data(base64Encoded: fixture.png), fixture.name)
            XCTAssertEqual(
                SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined(), fixture.sha256, fixture.name)
            let document = try Dust3DDocument(data: Dust3DDocument.emptyArchive())
                .applying(.setReferenceImagePNG(png))
            let prepared = try ReferenceColorRasterCodec.prepare(
                document: document, fittedSize: ReferencePixelSize(width: fixture.width, height: fixture.height))
            XCTAssertEqual(Array(prepared.raster.pixels), fixture.expected, fixture.name)
        }
    }

