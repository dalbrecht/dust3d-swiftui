import Dust3DEditorModel
import Foundation
import XCTest

final class MeshPreviewStateTests: XCTestCase {
    func testInitialFailureAndSuccessfulRetry() {
        var state = MeshPreviewState<String>()
        XCTAssertNil(state.value)
        XCTAssertNil(state.errorMessage)
        XCTAssertFalse(state.isGenerating)
        XCTAssertFalse(state.isStale)
        XCTAssertEqual(state.revision, 0)
        let first = UUID()
        state.begin(requestID: first)
        XCTAssertTrue(state.isGenerating)
        XCTAssertFalse(state.isStale)
        state.fail("Unsupported graph", requestID: first)
        XCTAssertNil(state.value)
        XCTAssertEqual(state.errorMessage, "Unsupported graph")
        XCTAssertFalse(state.isGenerating)
        XCTAssertFalse(state.isStale)
        let retry = UUID()
        state.begin(requestID: retry)
        XCTAssertNil(state.errorMessage)
        state.succeed("valid mesh", requestID: retry)
        XCTAssertEqual(state.value, "valid mesh")
        XCTAssertFalse(state.isGenerating)
        XCTAssertFalse(state.isStale)
        XCTAssertEqual(state.revision, 1)
    }

    func testUpdateAndFailureRetainLastMeshUntilRecovery() {
        var state = MeshPreviewState<String>()
        let first = UUID()
        state.begin(requestID: first)
        state.succeed("original", requestID: first)
        let update = UUID()
        state.begin(requestID: update)
        XCTAssertEqual(state.value, "original")
        XCTAssertTrue(state.isStale)
        state.fail("Cannot generate", requestID: update)
        XCTAssertEqual(state.value, "original")
        XCTAssertTrue(state.isStale)
        XCTAssertEqual(state.revision, 1)
        let recovery = UUID()
        state.begin(requestID: recovery)
        XCTAssertNil(state.errorMessage)
        state.succeed("new", requestID: recovery)
        XCTAssertEqual(state.value, "new")
        XCTAssertFalse(state.isStale)
        XCTAssertNil(state.errorMessage)
        XCTAssertEqual(state.revision, 2)
    }

    func testObsoleteAndDuplicateCompletionsCannotReplaceCurrentState() {
        var state = MeshPreviewState<String>()
        let old = UUID()
        let current = UUID()
        state.begin(requestID: old)
        state.begin(requestID: current)
        state.succeed("obsolete", requestID: old)
        state.fail("obsolete error", requestID: old)
        XCTAssertNil(state.value)
        XCTAssertNil(state.errorMessage)
        XCTAssertTrue(state.isGenerating)
        state.succeed("current", requestID: current)
        state.fail("late error", requestID: current)
        state.succeed("duplicate", requestID: current)
        XCTAssertEqual(state.value, "current")
        XCTAssertNil(state.errorMessage)
        XCTAssertEqual(state.revision, 1)
    }

    func testClearRemovesRetainedGeometryAndInvalidatesPendingWork() {
        var state = MeshPreviewState<String>()
        let first = UUID()
        state.begin(requestID: first)
        state.succeed("previous document", requestID: first)
        let pending = UUID()
        state.begin(requestID: pending)
        state.fail("failed", requestID: pending)
        state.clear()
        XCTAssertNil(state.value)
        XCTAssertNil(state.errorMessage)
        XCTAssertFalse(state.isGenerating)
        XCTAssertFalse(state.isStale)
        state.begin(requestID: pending)
        state.clear()
        state.succeed("old document", requestID: pending)
        state.fail("old failure", requestID: pending)
        XCTAssertNil(state.value)
        XCTAssertNil(state.errorMessage)
        XCTAssertFalse(state.isGenerating)
        XCTAssertEqual(state.revision, 1)
    }
}
