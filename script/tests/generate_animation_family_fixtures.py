#!/usr/bin/env python3
"""Reproduce bounded App animation fixtures using the recorded Core source generator."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import xml.etree.ElementTree as ET

CORE_REVISION = '0d93595fb359de8eecfd33046d1a7b09eafee46d'
FAMILIES = [
    ('bluebird', 'Bird', 'BirdWalk', 'BirdIdle', 'authored_core_example'),
    ('fox', 'Quadruped', 'QuadrupedWalk', 'QuadrupedIdle', 'authored_core_example'),
    ('goblin', 'Biped', 'BipedWalk', 'BipedIdle', 'authored_core_example'),
    ('goldfish', 'Fish', 'FishSwim', 'FishIdle', 'authored_core_example'),
    ('insect', 'Insect', 'InsectWalk', 'InsectIdle', 'synthetic_body_chain'),
    ('snake', 'Snake', 'SnakeSlither', 'SnakeIdle', 'synthetic_body_chain'),
    ('spider', 'Spider', 'SpiderWalk', 'SpiderIdle', 'synthetic_body_chain'),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--core', required=True, type=Path)
    parser.add_argument('--verify', action='store_true', help='Compare generated bytes without replacing files')
    arguments = parser.parse_args()
    core = arguments.core.resolve()
    revision = subprocess.check_output(['git', '-C', str(core), 'rev-parse', 'HEAD'], text=True).strip()
    if revision != CORE_REVISION:
        raise SystemExit('Reproduction requires Core ' + CORE_REVISION)
    toolkit = core / 'tools/agent_modeling'
    sys.path.insert(0, str(toolkit))
    from dust3d_agent.ds3 import build_document, write_ds3
    from dust3d_agent.spec import parse_spec
    import tempfile

    fixtures = Path(__file__).resolve().parents[2] / 'Tests/Dust3DKitTests/Fixtures/AnimationFamilies'
    rows = []
    for name, family, moving_type, idle_type, provenance in FAMILIES:
        source = fixtures / 'Sources' / (name + '.json')
        source_bytes = source.read_bytes()
        model, assets, _ = build_document(parse_spec(json.loads(source_bytes)))
        with tempfile.TemporaryDirectory(prefix='animation-fixture-') as directory:
            generated = Path(directory) / (name + '.ds3')
            write_ds3(str(generated), model, assets)
            archive = generated.read_bytes()
        if len(archive) > 128 * 1024:
            raise SystemExit('Fixture exceeds its 128 KiB source bound: ' + name)
        destination = fixtures / (name + '.ds3')
        if arguments.verify:
            if destination.read_bytes() != archive:
                raise SystemExit('Fixture bytes differ: ' + name)
        else:
            destination.write_bytes(archive)
        canvas = ET.fromstring(model)
        if canvas.attrib.get('rigType') != family:
            raise SystemExit('Unexpected rig family: ' + name)
        clips = {entry.attrib['type']: entry.attrib for entry in canvas.findall('animations/animation')}

        def clip(kind):
            metadata = clips[kind]
            return {
                'id': metadata['id'], 'type': kind, 'name': metadata['name'],
                'duration': float(metadata['durationSeconds']),
                'authoredFrameCount': int(float(metadata['frameCount'])),
            }

        rows.append({
            'name': name, 'family': family, 'provenance': provenance,
            'sourcePath': 'Sources/' + source.name,
            'sourceSHA256': hashlib.sha256(source_bytes).hexdigest(),
            'archivePath': destination.name, 'archiveSHA256': hashlib.sha256(archive).hexdigest(),
            'archiveBytes': len(archive), 'moving': clip(moving_type), 'idle': clip(idle_type),
        })
    tools = ['ds3.py', 'spec.py']
    manifest = {
        'coreRevision': CORE_REVISION,
        'generatorSources': {
            'tools/agent_modeling/dust3d_agent/' + name:
                hashlib.sha256((toolkit / 'dust3d_agent' / name).read_bytes()).hexdigest()
            for name in tools
        },
        'scope': 'Authored Core examples and synthetic chains, without upstream Qt differential provenance.',
        'families': rows,
    }
    encoded = (json.dumps(manifest, indent=2) + '\n').encode()
    manifest_path = fixtures / 'manifest.json'
    if arguments.verify:
        if manifest_path.read_bytes() != encoded:
            raise SystemExit('Fixture manifest differs')
    else:
        manifest_path.write_bytes(encoded)
    print('Verified' if arguments.verify else 'Generated', len(rows), 'bounded animation-family fixtures')


if __name__ == '__main__':
    main()
